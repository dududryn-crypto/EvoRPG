'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');
const { open, SCHEMA_VERSION } = require('../server/db');

test('migra banco da Alpha 1.0 (v1 → v3) preservando XP, moedas e acompanhamento', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'evolve-mig-'));
  const file = path.join(dir, 'evolve.db');
  const v1 = new DatabaseSync(file);
  v1.exec(`
    CREATE TABLE profile (id INTEGER PRIMARY KEY, name TEXT, timezone TEXT, rest_weekdays TEXT, character TEXT, last_seen_streak INTEGER, finalized_until TEXT, created_at TEXT);
    CREATE TABLE activities (id INTEGER PRIMARY KEY, name TEXT, attributes TEXT);
    CREATE TABLE rest_days (date TEXT PRIMARY KEY, reason TEXT);
    CREATE TABLE xp_events (id INTEGER PRIMARY KEY, attribute TEXT, amount INTEGER, multiplier REAL, source TEXT, source_id INTEGER, day TEXT, reason TEXT, ukey TEXT, created_at TEXT);
    CREATE TABLE coin_events (id INTEGER PRIMARY KEY, amount INTEGER, source TEXT, source_id INTEGER, day TEXT, reason TEXT, ukey TEXT, created_at TEXT);
    CREATE TABLE exercises (id INTEGER PRIMARY KEY, name TEXT, muscle_group TEXT);
    CREATE TABLE workouts (id INTEGER PRIMARY KEY, date TEXT, duration_min INTEGER, notes TEXT, created_at TEXT);
    CREATE TABLE workout_sets (id INTEGER PRIMARY KEY, workout_id INTEGER, exercise_id INTEGER, set_no INTEGER, reps INTEGER, weight REAL);
    CREATE TABLE metrics (id INTEGER PRIMARY KEY, key TEXT, name TEXT, unit TEXT, category TEXT, aggregation TEXT, direction TEXT, daily_target REAL, weekly_target REAL, builtin INTEGER);
    CREATE TABLE metric_logs (id INTEGER PRIMARY KEY, metric_id INTEGER, date TEXT, value REAL, note TEXT, created_at TEXT);
    CREATE TABLE sleep_logs (id INTEGER PRIMARY KEY, date TEXT, bed_time TEXT, wake_time TEXT, hours REAL, quality INTEGER, notes TEXT);
    CREATE TABLE achievements (key TEXT PRIMARY KEY, unlocked_at TEXT, day TEXT, seen INTEGER);
    CREATE TABLE inventory (item_id TEXT PRIMARY KEY, source TEXT, acquired_at TEXT);
    INSERT INTO profile VALUES (1, 'Luiz', 'America/Sao_Paulo', '[0]', '{"hair":"hair_long"}', 0, NULL, '2026-11-01 10:00:00');
    INSERT INTO activities VALUES (1, 'Ler', '{"intelectual":1}');
    INSERT INTO xp_events VALUES (1, 'intelectual', 120, 1, 'activity', 1, '2026-11-02', 'Ler', 'act:1:intelectual', '2026-11-02');
    INSERT INTO coin_events VALUES (1, 30, 'activity', 1, '2026-11-02', 'Ler', 'act:1', '2026-11-02');
    INSERT INTO exercises VALUES (1, 'Supino', NULL);
    INSERT INTO workouts VALUES (1, '2026-11-02', 50, NULL, '2026-11-02');
    INSERT INTO workout_sets VALUES (1, 1, 1, 1, 8, 60);
    INSERT INTO metrics VALUES (1, 'agua', 'Água', 'L', 'saude', 'sum', 'min', 3, NULL, 1);
    INSERT INTO metric_logs VALUES (1, 1, '2026-11-02', 2.5, NULL, '2026-11-02');
    INSERT INTO sleep_logs VALUES (1, '2026-11-02', '23:00', '07:00', 8, 4, NULL);
    INSERT INTO inventory VALUES ('wpn_iron', 'loja', '2026-11-02');
  `);
  v1.close();
  const db = open(file);
  assert.ok(db.migratedFrom && fs.existsSync(db.migratedFrom), 'backup criado');
  assert.equal(db.one('SELECT name FROM profile').name, 'Luiz');

  assert.equal(db.one('SELECT SUM(amount) s FROM xp_events').s, 120);
  assert.equal(db.one('SELECT SUM(amount) s FROM coin_events').s, 30);
  const kinds = db.all('SELECT kind, data FROM records').map((r) => r.kind).sort();
  assert.deepEqual(kinds, ['forca', 'hidratacao', 'sono']);
  const forca = JSON.parse(db.one("SELECT data FROM records WHERE kind = 'forca'").data);
  assert.equal(forca.exercises[0].name, 'Supino');
  assert.equal(forca.exercises[0].sets[0].weight, 60);
  assert.equal(db.one('SELECT weekdays FROM rest_rules').weekdays, '[0]');
  assert.equal(db.one("SELECT COUNT(*) n FROM inventory WHERE item_id = 'g_weapon'").n, 1, 'item antigo mapeado para o novo catálogo');
  assert.equal(JSON.parse(db.one('SELECT character FROM profile').character).hair, 'long');
  assert.equal(db.one("SELECT value FROM meta WHERE key = 'schema_version'").value, String(SCHEMA_VERSION));
  db.close();
  const again = open(file);
  assert.equal(again.migratedFrom, null, 'não migra duas vezes');
  again.close();
});

test('migra banco da Alpha 1.1 (v2 → v3): valores manuais viram registros detalhados', () => {
  const { LEGACY_SCHEMA } = require('../server/db');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'evolve-mig2-'));
  const file = path.join(dir, 'evolve.db');
  const d0 = open(file);
  d0.exec(LEGACY_SCHEMA);
  d0.exec(`INSERT INTO profile (id, name, timezone, character, created_on) VALUES (1, 'Luiz', 'America/Sao_Paulo', '{"hair":"hair_spiky","weapon":"wpn_axe"}', '2026-10-01');
    INSERT INTO goals (id, type, created_on) VALUES (1, 'leitura', '2026-10-01'), (2, 'proteinas', '2026-10-01');
    INSERT INTO goal_versions (goal_id, effective_from, period, target, unit, mode, days) VALUES (1, '2026-10-01', 'daily', 30, 'paginas', 'min', '[0,1,2,3,4,5,6]'), (2, '2026-10-01', 'daily', 140, 'g', 'min', '[0,1,2,3,4,5,6]');
    INSERT INTO day_entries (goal_id, date, status, value) VALUES (1, '2026-10-02', 'value', 25), (1, '2026-10-03', 'missed', NULL);
    INSERT INTO metrics (id, key, name, unit, builtin) VALUES (1, 'proteinas', 'Proteínas', 'g', 1);
    INSERT INTO metric_logs (metric_id, date, value) VALUES (1, '2026-10-02', 120);
    INSERT INTO inventory (item_id, source) VALUES ('wpn_axe', 'loja');
    UPDATE meta SET value = '2' WHERE key = 'schema_version';`);
  d0.close();
  const db = open(file);
  assert.ok(db.migratedFrom && fs.existsSync(db.migratedFrom), 'backup criado');
  const leit = JSON.parse(db.one("SELECT data FROM records WHERE kind = 'leitura'").data);
  assert.equal(leit.pages, 25);
  assert.equal(db.one("SELECT COUNT(*) n FROM day_entries").n, 1, 'marcação de descumprimento preservada');
  assert.equal(JSON.parse(db.one("SELECT data FROM records WHERE kind = 'refeicao'").data).protein, 120);
  assert.equal(db.one('SELECT unit FROM goal_versions WHERE goal_id = 2').unit, 'proteina');
  const ch = JSON.parse(db.one('SELECT character FROM profile').character);
  assert.equal(ch.hair, 'spiky');
  assert.equal(ch.weapon, 'wpn_axe');
  db.close();
});
